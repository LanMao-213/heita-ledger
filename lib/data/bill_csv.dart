/// 支付宝 / 微信账单 CSV 解析。
///
/// ## 为什么单独一层
///
/// 这三个理由决定了它必须是**纯函数**、不碰数据库也不碰 UI：
/// 1. 账单格式脏得超出想象（表头中英混排、说明行、金额带 ¥ 与千分位、
///    收/支列有空值），出错的方式有几十种，只有纯函数才测得起；
/// 2. 解析结果要**给用户逐行过目**，所以它不能边解析边写库；
/// 3. 同一份文件可能被导两次 —— 判定重复的逻辑必须能脱离数据库单测。
///
/// ## 编码：这里有一条**明确的取舍**
///
/// 支付宝导出的 CSV 常见 GBK，而 Dart 标准库只有 utf8 / latin1 / ascii，
/// **没有 GBK 编解码**。项目红线之一是「不新增依赖」，所以本版的处理是：
///
/// - 支持 UTF-8（含 BOM）、UTF-16LE/BE（含 BOM）；
/// - 探测到字节像 GBK（有 >0x7F 且非合法 UTF-8 序列）时**明确报错**，
///   并给出可操作的指引（用 Excel 另存为 UTF-8 CSV），
/// - **绝不**用 `allowMalformed` 硬解 —— 那样会把「锟斤拷」写进用户的账本，
///   是最坏的失败模式：用户看到乱码时，数据已经进库了。
///
/// 这条取舍写在 [BillParseError.encoding] 的文案里，用户看得见。
library;

import 'dart:convert';

import 'models.dart';

part 'bill/models.dart';
part 'bill/format.dart';
part 'bill/decode.dart';
part 'bill/parse.dart';
part 'bill/dedupe.dart';

/// 账单 CSV 解析器。全部静态纯函数，无状态。
abstract final class BillCsv {
  /// 解析字节流。
  ///
  /// 抛 [BillParseException] 的三种情况：编码、找不到表头、没有可导入行。
  static BillParseResult parse(List<int> bytes) => _parse(bytes);

  /// 金额解析：`¥32.00` / `-32.00` / `1,234.56` / `32.00元` 都要能认。
  ///
  /// 返回**带符号**的分值；认不出来返回 null（调用方据此判为说明行）。
  static int? parseAmount(String raw) => _parseAmount(raw);

  /// 日期解析：`2026-10-01 12:30:00` / `2026/10/1` / `2026-10-01`。
  static (String, String)? parseDate(String raw) => _parseDate(raw);

  /// 给每行和已有记录打分，标出「疑似重复」与「确定性重复」。
  ///
  /// ## 为什么不是「金额相等就算重复」
  ///
  /// 每天一杯 32 元的咖啡、每周一次 50 元的停车费 —— 金额天然会重复。
  /// 单靠金额判重，会把正常消费误判成重复账，而**误判的代价是不对称的**：
  /// 少导入一笔，用户丢的是钱；多导入一笔，用户随手删掉就行。
  ///
  /// ## 两档判据，各管一件事（不要合并成一套）
  ///
  /// | | 判据 | 用途 | 默认动作 |
  /// |---|---|---|---|
  /// | 确定性重复 | **日 + 分 + 对方** 三要素精确相等 | 挡"同一份账单导两次" | 不勾（可手动勾回） |
  /// | 疑似重复 | 多维打分 ≥ 55（金额/日期/方向/对方相似） | 提示"这两笔像不像同一笔" | 勾上（只标黄） |
  ///
  /// ★ 为什么确定性那一档必须**命中即抵扣**：库里有 1 笔「今天 32 元星巴克」，
  ///   文件里出现 2 笔同样的 —— 用户其实是上午下午各喝了一杯，只有 1 笔是旧的。
  ///   若用布尔集合，两行都会被判成"已存在"，第二笔真账就被默认排除了。
  ///   改成计数（命中一次减一），1 笔库记录只够认领 1 行，第 2 行回到正常态。
  ///   这就是"宁可漏报，不要误杀"的落点。
  ///
  /// ★ 指纹只取「日 + 分 + 对方」，**不取备注/商品**：备注常被用户手改，
  ///   同一个商家同一天同一金额才是幂等该认的边界；再放宽一定误杀。
  static void markDuplicates(List<BillRow> rows, List<Txn> existing) => _markDuplicates(rows, existing);
}
