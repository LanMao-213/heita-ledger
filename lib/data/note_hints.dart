const Map<String, List<String>> _incomeHints = {
  '工资': ['月薪', '补发工资', '加班费'],
  '奖金': ['年终奖', '季度奖', '绩效'],
  '兼职': ['稿费', '外包', '家教'],
  '理财': ['利息', '分红', '基金收益'],
  '红包': ['压岁钱', '过节红包'],
  '其他': ['报销', '退款'],
};

/// 取某个分类的候选名目；没有配置就返回空列表。
///
/// 转账没有分类，调用方不会传 [TxnType.transfer]；万一是转账也只会拿到空表。
List<String> noteHintsFor(TxnType type, String categoryName) {
  final table = type == TxnType.income ? _incomeHints : _expenseHints;
  return table[categoryName] ?? const <String>[];
}
