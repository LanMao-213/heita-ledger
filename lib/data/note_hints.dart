import 'models.dart';

/// 备注名目候选表：按「收支类型 + 分类名」查。
///
/// ★ 为什么不能只按分类名做 key：支出和收入各有一个「其他」，同名不同义，
///   用一张表会互相覆盖。所以拆成支出 / 收入两张。
///
/// 设计取舍（定稿于 2026-10-17 逐项确认）：
/// - **只覆盖种子分类**。用户自建分类查不到就返回空表，UI 不显示候选、不占位、不报错。
/// - key 用**分类名**而不是 category id：种子 id 虽然各设备一致，但用户改名本意就是
///   「这套词不适用了」，用名字反而符合直觉。
/// - 这里只有数据，不含任何 UI 假设 —— 用双轮盘还是 chip 展示都不影响本文件。
///
/// 词表口径（按确认结果）：
/// - 快递归「其他」不进购物；宽带归通讯不进居住；健身归其他不进娱乐；
/// - 医保（收入性质）、借出（非消费）、考试（与培训重复）、手机（耐用品）均不入表。
///
/// 支出 10 类共 62 词、收入 6 类共 16 词。

